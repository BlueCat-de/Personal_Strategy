#!/usr/bin/env python3
"""Incrementally update the offline A-share OHLCV dataset after market close.

The script updates an existing offline directory in the same schema generated by
``generate_offline_a_share_data.py``:

    date,symbol,open,high,low,close,volume,amount,turnover

It is designed for the daily workflow:

1. Keep the existing universe by default.
2. Re-fetch a short recent window for each symbol, not only one date. This
   protects the dataset from missing trading days and small front-adjustment
   changes.
3. Merge by (date, symbol), preserving leading zeros.
4. Rebuild ``prices_long.csv`` from per-symbol files.
"""

